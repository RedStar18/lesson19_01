#include <iostream>
#include <Windows.h>
#include <string>

int function(std::string str, int forbidden_length);

int main()
{
    setlocale(LC_ALL, "RUS");
    SetConsoleCP(1251);

    int len1, len2;
    std::string word;

    std::cout << "Введите запретную длину: ";
    std::cin >> len1;

    while (true)
    {
        std::cout << "Введите слово: ";
        std::cin >> word;

        try
        {
            len2 = function(word, len1);
            std::cout << "Длина слова \"" << word << "\" равна " << len2 << std::endl;
        }
        catch (const std::string& ex)
        {
            std::cout << "Вы ввели слово запретной длины! До свидания";
            return 0;
        }
    }
    

}

int function(std::string str, int forbidden_length)
{
    int len = str.length();

    if (len == forbidden_length)
    {
        throw std::string ("bad_length");
    }

    return len;
}

